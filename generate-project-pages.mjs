import fs from "node:fs/promises";
import path from "node:path";
import vm from "node:vm";
import { fileURLToPath } from "node:url";

const root = path.dirname(fileURLToPath(import.meta.url));
const siteOrigin = "https://meico-studio.github.io";
const context = { window: {} };
vm.runInNewContext(await fs.readFile(path.join(root, "projects.js"), "utf8"), context);
const projects = context.window.MEICO_PROJECTS;

const slugify = (value) => String(value || "project")
  .normalize("NFKD")
  .replace(/[\u0300-\u036f]/g, "")
  .toLowerCase()
  .replace(/[^a-z0-9]+/g, "-")
  .replace(/^-|-$/g, "");

const escapeHTML = (value) => String(value ?? "").replace(/[&<>"']/g, (char) => ({
  "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;"
})[char]);

for (const project of projects) {
  const slug = slugify(project.id || project.title);
  const route = `/projects/${slug}/`;
  const canonical = `${siteOrigin}${route}`;
  const title = `${project.title} — Meico Studio`;
  const description = project.description || `${project.title}, a motion design project by Meico Studio.`;
  const posterPath = `../../${project.poster}`;
  const posterUrl = `${siteOrigin}/${project.poster}`;
  const videoPath = `../../${project.video}`;
  const subject = encodeURIComponent(`Project inquiry — ${project.title} | Meico Studio`);
  const body = encodeURIComponent(`Hi Meico Studio,\n\nI’m interested in the ${project.title} project.\n\n${canonical}`);
  const homeProjectUrl = `${siteOrigin}/?project=${encodeURIComponent(slug)}`;

  const html = `<!doctype html>
<!-- Generated by generate-project-pages.mjs from projects.js. -->
<html lang="en">
<head>
  <meta charset="utf-8">
  <meta name="viewport" content="width=device-width, initial-scale=1">
  <meta name="theme-color" content="#f7f7f5">
  <meta name="description" content="${escapeHTML(description)}">
  <title>${escapeHTML(title)}</title>
  <link rel="canonical" href="${canonical}">
  <link rel="icon" type="image/svg+xml" href="../../assets/favicon.svg">
  <link rel="stylesheet" href="../../styles.css?v=project-share-meta-20261019">
  <meta property="og:type" content="website">
  <meta property="og:site_name" content="Meico Studio">
  <meta property="og:title" content="${escapeHTML(title)}">
  <meta property="og:description" content="${escapeHTML(description)}">
  <meta property="og:url" content="${canonical}">
  <meta property="og:image" content="${posterUrl}">
  <meta property="og:image:alt" content="${escapeHTML(project.title)} animation preview">
  <meta property="og:image:type" content="image/jpeg">
  <meta property="og:image:width" content="960">
  <meta property="og:image:height" content="540">
  <meta name="twitter:card" content="summary_large_image">
  <meta name="twitter:title" content="${escapeHTML(title)}">
  <meta name="twitter:description" content="${escapeHTML(description)}">
  <meta name="twitter:image" content="${posterUrl}">
</head>
<body class="project-share-page">
  <header class="project-share-header">
    <a class="project-share-brand" href="${siteOrigin}/">Meico Studio</a>
    <a class="project-share-back" href="${siteOrigin}/#work">All work</a>
  </header>
  <main class="project-share-main">
    <div class="project-share-media">
      <video controls playsinline preload="metadata" poster="${escapeHTML(posterPath)}">
        <source src="${escapeHTML(videoPath)}" type="video/mp4">
      </video>
    </div>
    <section class="project-share-info" aria-labelledby="project-title">
      <div>
        <p class="project-share-category">${escapeHTML(project.category || "Motion design")}</p>
        <h1 id="project-title">${escapeHTML(project.title)}</h1>
        <p class="project-share-description">${escapeHTML(description)}</p>
      </div>
      <div class="project-share-actions">
        <a href="${homeProjectUrl}">View in portfolio</a>
        <a href="mailto:info.meicostudio@gmail.com?subject=${subject}&amp;body=${body}">Email this project</a>
      </div>
    </section>
  </main>
  <footer class="project-share-footer">© ${new Date().getFullYear()} Meico Studio</footer>
</body>
</html>
`;

  const directory = path.join(root, "projects", slug);
  await fs.mkdir(directory, { recursive: true });
  await fs.writeFile(path.join(directory, "index.html"), html);
}

console.log(`Generated ${projects.length} project share pages.`);
